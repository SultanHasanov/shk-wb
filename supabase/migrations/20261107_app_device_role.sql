-- Роль компьютера в аккаунте «Помощника ПВЗ» (профиль программы → «Пункты и компьютеры»).
--   owner — компьютер владельца: видит все ПК и пункты, загружает копии баз, управляет аккаунтом;
--   work  — компьютер сотрудника пункта: видит только себя, раздаёт свою базу WB компьютерам владельца,
--           не загружает чужие базы и не управляет аккаунтом;
--   null  — роль не назначена (ПК, вошедшие до этой версии): ведёт себя как owner, владельцу показывается
--           подсказка назначить роль.
-- Новый ПК получает work (первый ПК пустого аккаунта — owner), см. server/_app-account.js registerDevice.
alter table public.app_devices
  add column if not exists role text check (role in ('owner', 'work'));
