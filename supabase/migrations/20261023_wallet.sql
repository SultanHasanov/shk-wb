begin;

-- Баланс (кошелёк) пользователя в рублях. Пополняется заказом product_kind='wallet_topup'
-- (с бонусом за сумму), тратится в Telegram-боте: генерации стикеров, «Кто поставил оценку»,
-- пакеты подборов, ключи «Печати ячеек», подписка «Помощника ПВЗ».
--
-- Покупка с баланса — обычный заказ payment_orders с amount=0, gross_amount=0 и
-- wallet_paid_kopecks=<цена>: выдача идёт штатными complete_*_order, реферальная комиссия
-- и выручка считаются один раз — с пополнения, а не с покупок из него.

create table if not exists public.wallet_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance_kopecks bigint not null default 0 check (balance_kopecks >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.wallet_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null check (kind in ('topup','bonus','spend','refund','admin')),
  amount_kopecks bigint not null,
  order_id uuid references public.payment_orders(id) on delete set null,
  event_key text not null unique,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists wallet_ledger_user_idx on public.wallet_ledger(user_id, created_at desc);

alter table public.wallet_accounts enable row level security;
alter table public.wallet_ledger enable row level security;
drop policy if exists wallet_accounts_own on public.wallet_accounts;
create policy wallet_accounts_own on public.wallet_accounts for select to authenticated using (user_id = auth.uid());
drop policy if exists wallet_ledger_own on public.wallet_ledger;
create policy wallet_ledger_own on public.wallet_ledger for select to authenticated using (user_id = auth.uid());

alter table public.payment_orders add column if not exists wallet_topup_kopecks bigint
  check (wallet_topup_kopecks is null or wallet_topup_kopecks > 0);
alter table public.payment_orders add column if not exists wallet_paid_kopecks bigint not null default 0
  check (wallet_paid_kopecks >= 0);

alter table public.payment_orders drop constraint if exists payment_orders_product_kind_check;
alter table public.payment_orders add constraint payment_orders_product_kind_check check
  (product_kind in ('stickers','program','program_license','cell_print_program','cell_print_license','cell_print_bundle','individual_stickers','app_subscription','app_addon','bot_reviews','wallet_topup'));

alter table public.payment_orders drop constraint if exists payment_orders_product_quantity_check;
alter table public.payment_orders add constraint payment_orders_product_quantity_check check (
  (product_kind='stickers' and range_quantity+custom_quantity>0)
  or (product_kind in ('program','program_license','cell_print_program','cell_print_license','cell_print_bundle','individual_stickers','app_subscription','app_addon','bot_reviews','wallet_topup')
      and range_quantity=0 and custom_quantity=0)
);

-- Движение по счёту. Повтор с тем же event_key ничего не меняет (идемпотентность).
-- Возвращает {ok, balance, duplicate}. ok=false — не хватило денег, ничего не списано.
create or replace function public.wallet_move(
  p_user uuid, p_kopecks bigint, p_kind text, p_event_key text,
  p_order uuid default null, p_details jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  current_balance bigint;
begin
  if p_user is null or p_kopecks is null or p_kopecks = 0 or p_event_key is null then
    raise exception 'Invalid wallet movement';
  end if;
  insert into public.wallet_accounts(user_id) values (p_user) on conflict (user_id) do nothing;
  select balance_kopecks into current_balance from public.wallet_accounts where user_id = p_user for update;
  if exists (select 1 from public.wallet_ledger where event_key = p_event_key) then
    return jsonb_build_object('ok', true, 'duplicate', true, 'balance', current_balance);
  end if;
  if current_balance + p_kopecks < 0 then
    return jsonb_build_object('ok', false, 'duplicate', false, 'balance', current_balance);
  end if;
  update public.wallet_accounts set balance_kopecks = balance_kopecks + p_kopecks, updated_at = now()
   where user_id = p_user returning balance_kopecks into current_balance;
  insert into public.wallet_ledger(user_id, kind, amount_kopecks, order_id, event_key, details)
    values (p_user, p_kind, p_kopecks, p_order, p_event_key, coalesce(p_details, '{}'::jsonb));
  return jsonb_build_object('ok', true, 'duplicate', false, 'balance', current_balance);
end;
$$;

-- Оплаченное пополнение → деньги и бонус на счёт. Идемпотентно по event_key.
create or replace function public.complete_wallet_topup_order(p_order_id uuid)
returns bigint language plpgsql security definer set search_path=public as $$
declare
  order_row public.payment_orders;
  paid bigint;
  bonus bigint;
  result jsonb;
begin
  perform pg_advisory_xact_lock(hashtext(p_order_id::text));
  select * into order_row from public.payment_orders where id = p_order_id and product_kind = 'wallet_topup' for update;
  if not found then raise exception 'Wallet top-up order not found'; end if;
  if order_row.user_id is null then raise exception 'Wallet top-up requires an account'; end if;
  if order_row.wallet_topup_kopecks is null then raise exception 'Invalid wallet top-up order'; end if;
  paid := round(order_row.gross_amount * 100)::bigint;
  bonus := greatest(0, order_row.wallet_topup_kopecks - paid);
  result := public.wallet_move(order_row.user_id, order_row.wallet_topup_kopecks - bonus, 'topup',
                               'topup:' || p_order_id::text, p_order_id, '{}'::jsonb);
  if bonus > 0 then
    result := public.wallet_move(order_row.user_id, bonus, 'bonus', 'topup-bonus:' || p_order_id::text, p_order_id, '{}'::jsonb);
  end if;
  update public.payment_orders set status = 'succeeded', paid_at = coalesce(paid_at, now()), updated_at = now()
   where id = p_order_id;
  return (result->>'balance')::bigint;
end;
$$;

-- Оплата заказа с баланса: списывает wallet_paid_kopecks. ok=false — не хватает денег.
create or replace function public.wallet_pay_order(p_order_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  order_row public.payment_orders;
begin
  select * into order_row from public.payment_orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if order_row.user_id is null or order_row.wallet_paid_kopecks <= 0 then raise exception 'Order is not a wallet order'; end if;
  if order_row.amount <> 0 then raise exception 'Wallet order must have zero amount'; end if;
  return public.wallet_move(order_row.user_id, -order_row.wallet_paid_kopecks, 'spend', 'pay:' || p_order_id::text,
                            p_order_id, jsonb_build_object('productKind', order_row.product_kind));
end;
$$;

-- Вернуть деньги за заказ с баланса, который не удалось выдать.
create or replace function public.wallet_refund_order(p_order_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  order_row public.payment_orders;
begin
  select * into order_row from public.payment_orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if order_row.fulfillment_status = 'fulfilled' then raise exception 'Order already fulfilled'; end if;
  if not exists (select 1 from public.wallet_ledger where event_key = 'pay:' || p_order_id::text) then
    return jsonb_build_object('ok', false, 'reason', 'not_paid');
  end if;
  update public.payment_orders set status = 'canceled', updated_at = now() where id = p_order_id;
  return public.wallet_move(order_row.user_id, order_row.wallet_paid_kopecks, 'refund', 'refund:' || p_order_id::text,
                            p_order_id, '{}'::jsonb);
end;
$$;

-- Разовое списание (без заказа): «Кто поставил оценку».
create or replace function public.wallet_spend(p_user uuid, p_kopecks bigint, p_event_key text, p_details jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
begin
  if p_kopecks is null or p_kopecks <= 0 then raise exception 'Invalid amount'; end if;
  return public.wallet_move(p_user, -p_kopecks, 'spend', p_event_key, null, p_details);
end;
$$;

-- «Кто поставил оценку»: 25 ₽ с баланса за клиента в этом ПВЗ, повтор того же автора бесплатный.
-- Сигнатура та же, что в 20261022, — бот вызывает её как раньше.
create or replace function public.bot_review_spend(p_user uuid, p_point bigint, p_client bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  result jsonb;
begin
  perform pg_advisory_xact_lock(hashtext('bot_review:' || p_user::text));
  if exists (select 1 from public.bot_review_reveals
              where user_id = p_user and point_id = p_point and client_id = p_client) then
    return jsonb_build_object('ok', true, 'free', true,
      'balance', coalesce((select balance_kopecks from public.wallet_accounts where user_id = p_user), 0));
  end if;
  result := public.wallet_spend(p_user, 2500, 'review:' || p_user::text || ':' || p_point::text || ':' || p_client::text,
                                jsonb_build_object('point', p_point, 'client', p_client));
  if not (result->>'ok')::boolean then
    return jsonb_build_object('ok', false, 'free', false, 'balance', (result->>'balance')::bigint);
  end if;
  insert into public.bot_review_reveals(user_id, point_id, client_id) values (p_user, p_point, p_client)
    on conflict do nothing;
  return jsonb_build_object('ok', true, 'free', false, 'balance', (result->>'balance')::bigint);
end;
$$;

-- Ручное начисление/списание (поддержка, проверка).
create or replace function public.admin_wallet_adjust(p_user uuid, p_kopecks bigint, p_note text default '')
returns jsonb language plpgsql security definer set search_path=public as $$
begin
  return public.wallet_move(p_user, p_kopecks, 'admin', 'admin:' || gen_random_uuid()::text, null,
                            jsonb_build_object('note', coalesce(p_note, '')));
end;
$$;

revoke all on function public.wallet_move(uuid,bigint,text,text,uuid,jsonb) from public, anon, authenticated;
revoke all on function public.complete_wallet_topup_order(uuid) from public, anon, authenticated;
revoke all on function public.wallet_pay_order(uuid) from public, anon, authenticated;
revoke all on function public.wallet_refund_order(uuid) from public, anon, authenticated;
revoke all on function public.wallet_spend(uuid,bigint,text,jsonb) from public, anon, authenticated;
revoke all on function public.admin_wallet_adjust(uuid,bigint,text) from public, anon, authenticated;
grant execute on function public.wallet_move(uuid,bigint,text,text,uuid,jsonb) to service_role;
grant execute on function public.complete_wallet_topup_order(uuid) to service_role;
grant execute on function public.wallet_pay_order(uuid) to service_role;
grant execute on function public.wallet_refund_order(uuid) to service_role;
grant execute on function public.wallet_spend(uuid,bigint,text,jsonb) to service_role;
grant execute on function public.admin_wallet_adjust(uuid,bigint,text) to service_role;

commit;
