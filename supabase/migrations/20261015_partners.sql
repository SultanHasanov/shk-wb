-- Ключ печати ячеек: CP-XXXX-XXXX-XXXX. Срок и число ПК сервер проверяет по
-- тем же спискам, что у админки (server/_admin-grants.js).
create or replace function public.partner_issue_cell_license(
  p_partner uuid, p_days integer, p_devices integer, p_scope text, p_note text, p_rate numeric, p_price_kzt numeric default null
) returns public.cell_print_licenses language plpgsql security definer set search_path=public as $$
declare
  cost numeric;
  generated_key text;
  created public.cell_print_licenses;
begin
  if p_days < 1 or p_days > 4000 or p_devices < 1 or coalesce(p_rate, 0) <= 0 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  if p_scope not in ('wb','ozon','both') then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  cost := public.partner_take(p_partner, 'cell', p_days * p_devices);
  loop
    generated_key := 'CP-' || upper(substr(md5(random()::text || clock_timestamp()::text),1,4)) || '-' ||
      upper(substr(md5(random()::text || clock_timestamp()::text),1,4)) || '-' ||
      upper(substr(md5(random()::text || clock_timestamp()::text),1,4));
    begin
      insert into public.cell_print_licenses(key, duration_days, device_limit, marketplace_scope, active, source, note, partner_id)
        values (generated_key, p_days, p_devices, p_scope, true, 'partner', left(coalesce(btrim(p_note), ''), 200), p_partner)
        returning * into created;
      exit;
    exception when unique_violation then null;
    end;
  end loop;
  perform public.partner_log(p_partner, 'cell', -(p_days * p_devices), 'issue', created.id, created.key, created.note, cost, p_rate, p_price_kzt);
  return created;
end;
$$;

-- Сводка расчётов: сколько партнёр должен владельцу и сколько выручил в тенге.
create or replace function public.partner_balance(p_partner uuid)
returns jsonb language sql stable security definer set search_path=public as $$
  select jsonb_build_object(
    'issuedRub', coalesce((select sum(cost_rub) from public.partner_ledger where partner_id = p_partner and kind in ('issue','topup')), 0),
    'paidRub', coalesce((select sum(amount_rub) from public.partner_payments where partner_id = p_partner), 0),
    'revenueKzt', coalesce((select sum(price_kzt) from public.partner_ledger where partner_id = p_partner and kind in ('issue','topup')), 0)
  );
$$;

do $$
declare
  fn text;
begin
  foreach fn in array array[
    'public.partner_grant(uuid, text, integer, text)',
    'public.partner_take(uuid, text, integer)',
    'public.partner_price_kzt(uuid, numeric, numeric, numeric)',
    'public.partner_log(uuid, text, integer, text, bigint, text, text, numeric, numeric, numeric)',
    'public.partner_issue_sticker_code(uuid, text, integer, numeric, numeric)',
    'public.partner_topup_sticker_code(uuid, bigint, integer, numeric, numeric)',
    'public.partner_issue_program_key(uuid, integer, text, numeric, numeric)',
    'public.partner_topup_program_key(uuid, bigint, integer, numeric, numeric)',
    'public.partner_issue_cell_license(uuid, integer, integer, text, text, numeric, numeric)',
    'public.partner_balance(uuid)'
  ] loop
    execute format('revoke all on function %s from public, anon, authenticated', fn);
    execute format('grant execute on function %s to service_role', fn);
  end loop;
end;
$$;

