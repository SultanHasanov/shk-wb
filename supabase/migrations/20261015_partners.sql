begin;

-- Партнёры: обычные аккаунты сайта, которым владелец выдал пул на выпуск кодов
-- и ключей для своих клиентов (первый — партнёр из Казахстана).
--
-- Пул хранится счётчиками granted/used, а каждое движение пишется в
-- partner_ledger: счётчики дают быстрый остаток и атомарную проверку под
-- for update, журнал — разбор «куда ушло» без пересчёта по трём таблицам.
-- cell-пул считается в днях·ПК: ключ на 30 дней на 2 ПК тратит 60.
--
-- Деньги. Партнёр должен владельцу рубли по своей оптовой цене за единицу
-- (price_*_rub, задаёт владелец), а с клиента берёт тенге со своей наценкой.
-- Каждый выпуск фиксирует в журнале cost_rub, курс и price_kzt на момент
-- выпуска: курс и цены потом меняются, а долг за прошлые выпуски — нет.
-- Оплаты партнёра владелец отмечает в partner_payments; долг = выпуски − оплаты.

create table if not exists public.partners (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  country text not null default 'KZ' check (country ~ '^[A-Z]{2}$'),
  currency text not null default 'KZT' check (currency in ('RUB','KZT')),
  active boolean not null default true,
  note text not null default '' check (char_length(note) <= 500),
  sticker_granted integer not null default 0 check (sticker_granted >= 0),
  sticker_used integer not null default 0 check (sticker_used >= 0 and sticker_used <= sticker_granted),
  program_granted integer not null default 0 check (program_granted >= 0),
  program_used integer not null default 0 check (program_used >= 0 and program_used <= program_granted),
  cell_granted integer not null default 0 check (cell_granted >= 0),
  cell_used integer not null default 0 check (cell_used >= 0 and cell_used <= cell_granted),
  -- Оптовые цены за единицу по умолчанию — минимальные цены сайта за единицу:
  -- 135 ₽ / 500 генераций, 150 ₽ / 20 итераций, 150 ₽ / 30 дней на 1 ПК.
  price_sticker_rub numeric(10,4) not null default 0.27 check (price_sticker_rub >= 0),
  price_program_rub numeric(10,4) not null default 7.5 check (price_program_rub >= 0),
  price_cell_rub numeric(10,4) not null default 5 check (price_cell_rub >= 0),
  -- Наценку задаёт сам партнёр: это его цена для клиента, владельцу она не важна.
  markup_percent numeric(7,2) not null default 0 check (markup_percent between 0 and 10000),
  created_at timestamptz not null default now()
);

create table if not exists public.partner_ledger (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.partners(id) on delete cascade,
  resource text not null check (resource in ('sticker','program','cell')),
  delta integer not null check (delta <> 0),
  kind text not null check (kind in ('grant','issue','topup')),
  ref_id bigint,
  ref_label text,
  actor text not null check (actor in ('owner','partner')),
  note text not null default '' check (char_length(note) <= 200),
  cost_rub numeric(12,2),
  kzt_per_rub numeric(10,4),
  price_kzt numeric(14,2),
  created_at timestamptz not null default now()
);

create index if not exists partner_ledger_partner_idx
  on public.partner_ledger(partner_id, created_at desc);

create table if not exists public.partner_payments (
  id bigint generated by default as identity primary key,
  partner_id uuid not null references public.partners(id) on delete cascade,
  amount_rub numeric(12,2) not null check (amount_rub <> 0),
  note text not null default '' check (char_length(note) <= 200),
  created_at timestamptz not null default now()
);

create index if not exists partner_payments_partner_idx
  on public.partner_payments(partner_id, created_at desc);

alter table public.sticker_access_codes
  add column if not exists partner_id uuid references public.partners(id) on delete set null;
alter table public.license_keys
  add column if not exists partner_id uuid references public.partners(id) on delete set null;
alter table public.cell_print_licenses
  add column if not exists partner_id uuid references public.partners(id) on delete set null;

create index if not exists sticker_access_codes_partner_idx
  on public.sticker_access_codes(partner_id) where partner_id is not null;
create index if not exists license_keys_partner_idx
  on public.license_keys(partner_id) where partner_id is not null;
create index if not exists cell_print_licenses_partner_idx
  on public.cell_print_licenses(partner_id) where partner_id is not null;

-- Настройки сайта, которые владелец меняет из админки без деплоя (курс тенге).
create table if not exists public.site_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);
insert into public.site_settings(key, value) values ('kzt_per_rub', '5.5'::jsonb)
  on conflict (key) do nothing;

alter table public.partners enable row level security;
alter table public.partner_ledger enable row level security;
alter table public.partner_payments enable row level security;
alter table public.site_settings enable row level security;
revoke all on table public.partners, public.partner_ledger, public.partner_payments, public.site_settings
  from public, anon, authenticated;
grant select, insert, update, delete on table public.partners, public.partner_ledger, public.partner_payments, public.site_settings
  to service_role;

-- Пополнение и списание пула владельцем. Списать можно только неизрасходованное.
create or replace function public.partner_grant(p_partner uuid, p_resource text, p_amount integer, p_note text default '')
returns public.partners language plpgsql security definer set search_path=public as $$
declare
  row_ public.partners;
begin
  if p_amount = 0 or abs(p_amount) > 10000000 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  select * into row_ from public.partners where id = p_partner for update;
  if not found then raise exception 'PARTNER_NOT_FOUND'; end if;
  if p_resource = 'sticker' then
    if row_.sticker_granted + p_amount < row_.sticker_used then raise exception 'PARTNER_BELOW_USED'; end if;
    update public.partners set sticker_granted = sticker_granted + p_amount where id = p_partner returning * into row_;
  elsif p_resource = 'program' then
    if row_.program_granted + p_amount < row_.program_used then raise exception 'PARTNER_BELOW_USED'; end if;
    update public.partners set program_granted = program_granted + p_amount where id = p_partner returning * into row_;
  elsif p_resource = 'cell' then
    if row_.cell_granted + p_amount < row_.cell_used then raise exception 'PARTNER_BELOW_USED'; end if;
    update public.partners set cell_granted = cell_granted + p_amount where id = p_partner returning * into row_;
  else
    raise exception 'PARTNER_BAD_RESOURCE';
  end if;
  insert into public.partner_ledger(partner_id, resource, delta, kind, actor, note)
    values (p_partner, p_resource, p_amount, 'grant', 'owner', left(coalesce(p_note, ''), 200));
  return row_;
end;
$$;

-- Общая часть выпуска: блокирует активного партнёра, списывает пул и
-- возвращает оптовую стоимость списанного в рублях по текущей цене партнёра.
create or replace function public.partner_take(p_partner uuid, p_resource text, p_amount integer)
returns numeric language plpgsql security definer set search_path=public as $$
declare
  row_ public.partners;
begin
  if p_amount < 1 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  select * into row_ from public.partners where id = p_partner for update;
  if not found or not row_.active then raise exception 'PARTNER_INACTIVE'; end if;
  if p_resource = 'sticker' then
    if row_.sticker_granted - row_.sticker_used < p_amount then raise exception 'PARTNER_POOL_EXHAUSTED'; end if;
    update public.partners set sticker_used = sticker_used + p_amount where id = p_partner;
    return round(p_amount * row_.price_sticker_rub, 2);
  elsif p_resource = 'program' then
    if row_.program_granted - row_.program_used < p_amount then raise exception 'PARTNER_POOL_EXHAUSTED'; end if;
    update public.partners set program_used = program_used + p_amount where id = p_partner;
    return round(p_amount * row_.price_program_rub, 2);
  elsif p_resource = 'cell' then
    if row_.cell_granted - row_.cell_used < p_amount then raise exception 'PARTNER_POOL_EXHAUSTED'; end if;
    update public.partners set cell_used = cell_used + p_amount where id = p_partner;
    return round(p_amount * row_.price_cell_rub, 2);
  end if;
  raise exception 'PARTNER_BAD_RESOURCE';
end;
$$;

-- Цена клиенту в тенге: своя от партнёра или курс × стоимость × (1 + наценка),
-- округлённая до целого тенге.
create or replace function public.partner_price_kzt(p_partner uuid, p_cost numeric, p_rate numeric, p_price_kzt numeric)
returns numeric language sql stable security definer set search_path=public as $$
  select case
    when p_price_kzt is not null and p_price_kzt >= 0 then round(p_price_kzt, 2)
    else round(p_cost * p_rate * (1 + p.markup_percent / 100))
  end
  from public.partners p where p.id = p_partner;
$$;

create or replace function public.partner_log(
  p_partner uuid, p_resource text, p_delta integer, p_kind text, p_ref_id bigint, p_ref_label text,
  p_note text, p_cost numeric, p_rate numeric, p_price_kzt numeric
) returns void language plpgsql security definer set search_path=public as $$
begin
  insert into public.partner_ledger(partner_id, resource, delta, kind, ref_id, ref_label, actor, note, cost_rub, kzt_per_rub, price_kzt)
    values (p_partner, p_resource, p_delta, p_kind, p_ref_id, p_ref_label, 'partner', left(coalesce(p_note, ''), 200),
            p_cost, p_rate, public.partner_price_kzt(p_partner, p_cost, p_rate, p_price_kzt));
end;
$$;

-- Код стикеров: 6 цифр, как у покупки (20260908_six_digit_access_codes.sql).
create or replace function public.partner_issue_sticker_code(
  p_partner uuid, p_name text, p_limit integer, p_rate numeric, p_price_kzt numeric default null
) returns public.sticker_access_codes language plpgsql security definer set search_path=public as $$
declare
  cost numeric;
  generated_code text;
  created public.sticker_access_codes;
begin
  if p_limit < 1 or p_limit > 100000 or coalesce(p_rate, 0) <= 0 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  cost := public.partner_take(p_partner, 'sticker', p_limit);
  loop
    generated_code := lpad(floor(random() * 1000000)::integer::text, 6, '0');
    begin
      insert into public.sticker_access_codes(code, name, active, generation_limit, partner_id)
        values (generated_code, left(coalesce(nullif(btrim(p_name), ''), 'Код партнёра'), 120), true, p_limit, p_partner)
        returning * into created;
      exit;
    exception when unique_violation then null;
    end;
  end loop;
  perform public.partner_log(p_partner, 'sticker', -p_limit, 'issue', created.id, created.code, created.name, cost, p_rate, p_price_kzt);
  return created;
end;
$$;

create or replace function public.partner_topup_sticker_code(
  p_partner uuid, p_code_id bigint, p_add integer, p_rate numeric, p_price_kzt numeric default null
) returns public.sticker_access_codes language plpgsql security definer set search_path=public as $$
declare
  cost numeric;
  target public.sticker_access_codes;
begin
  if p_add < 1 or p_add > 100000 or coalesce(p_rate, 0) <= 0 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  select * into target from public.sticker_access_codes
    where id = p_code_id and partner_id = p_partner for update;
  if not found then raise exception 'PARTNER_ITEM_NOT_FOUND'; end if;
  cost := public.partner_take(p_partner, 'sticker', p_add);
  update public.sticker_access_codes set generation_limit = generation_limit + p_add
    where id = p_code_id returning * into target;
  perform public.partner_log(p_partner, 'sticker', -p_add, 'topup', target.id, target.code, target.name, cost, p_rate, p_price_kzt);
  return target;
end;
$$;

-- Ключ «Подбора кодов»: тот же формат WBPK-, что у покупки (20260904).
create or replace function public.partner_issue_program_key(
  p_partner uuid, p_iterations integer, p_note text, p_rate numeric, p_price_kzt numeric default null
) returns public.license_keys language plpgsql security definer set search_path=public as $$
declare
  cost numeric;
  generated_key text;
  created public.license_keys;
begin
  if p_iterations < 1 or p_iterations > 100000 or coalesce(p_rate, 0) <= 0 then raise exception 'PARTNER_BAD_AMOUNT'; end if;
  cost := public.partner_take(p_partner, 'program', p_iterations);
  loop
    generated_key := 'WBPK-' || upper(substr(md5(random()::text || clock_timestamp()::text),1,4)) || '-' ||
      upper(substr(md5(random()::text || clock_timestamp()::text),1,4)) || '-' ||
      upper(substr(md5(random()::text || clock_timestamp()::text),1,4));
    begin
      insert into public.license_keys(key, usage_limit, used, active, note, partner_id)
        values (generated_key, p_iterations, 0, true, left(coalesce(btrim(p_note), ''), 200), p_partner)
        returning * into created;
      exit;
    exception when unique_violation then null;
    end;
  end loop;
  perform public.partner_log(p_partner, 'program', -p_iterations, 'issue', created.id, created.key, created.note, cost, p_rate, p_price_kzt);
  return created;
end;
$$;

