-- «ПВЗ Принт» (бывш. «Печать ячеек») 2.2: пробный период 7 дней и пауза ключа.
-- Пробный: один на компьютер и один на аккаунт, ключ source='trial', WB+Ozon, 1 ПК.
-- Пауза: до 2 раз в календарный месяц (МСК), до 14 дней каждая; дни на паузе не
-- расходуются — при снятии expires_at сдвигается на фактическую длину паузы.
begin;

alter table public.cell_print_licenses
  add column if not exists paused_at timestamptz,
  add column if not exists pause_until timestamptz;

create table if not exists public.cell_print_trial_claims (
  device_hash text primary key check (length(device_hash) = 64),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  license_id bigint references public.cell_print_licenses(id) on delete set null,
  claimed_at timestamptz not null default now()
);
alter table public.cell_print_trial_claims enable row level security;
revoke all on table public.cell_print_trial_claims from anon, authenticated;
grant select, insert, update, delete on table public.cell_print_trial_claims to service_role;

create table if not exists public.cell_print_pauses (
  id bigint generated by default as identity primary key,
  license_id bigint not null references public.cell_print_licenses(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  shifted interval
);
create index if not exists cell_print_pauses_license_idx on public.cell_print_pauses(license_id, started_at desc);
alter table public.cell_print_pauses enable row level security;
revoke all on table public.cell_print_pauses from anon, authenticated;
grant select, insert, update, delete on table public.cell_print_pauses to service_role;

-- Сколько пауз осталось в этом календарном месяце (по Москве).
create or replace function public.cell_print_pauses_left(p_license bigint)
returns integer language sql stable security definer set search_path=public as $$
  select greatest(0, 2 - count(*)::integer) from public.cell_print_pauses
  where license_id=p_license
    and started_at >= (date_trunc('month', now() at time zone 'Europe/Moscow') at time zone 'Europe/Moscow');
$$;

-- Снять паузу: досрочно (p_force) или когда истекли 14 дней. Срок сдвигается на длину паузы.
create or replace function public.cell_print_settle_pause(p_license bigint, p_force boolean default false)
returns void language plpgsql security definer set search_path=public as $$
declare lic public.cell_print_licenses; stop_at timestamptz;
begin
  select * into lic from public.cell_print_licenses where id=p_license for update;
  if not found or lic.paused_at is null then return; end if;
  if not p_force and lic.pause_until > now() then return; end if;
  stop_at := least(now(), lic.pause_until);
  update public.cell_print_licenses set
    expires_at = case when expires_at is null then null else expires_at + (stop_at - paused_at) end,
    paused_at = null, pause_until = null
  where id=lic.id;
  update public.cell_print_pauses set ended_at=stop_at, shifted=stop_at - lic.paused_at
    where license_id=lic.id and ended_at is null;
end;$$;

-- Все истёкшие паузы (крон раз в сутки; activate/keys снимают свою сами).
create or replace function public.cell_print_settle_expired_pauses()
returns integer language plpgsql security definer set search_path=public as $$
declare r record; n integer := 0;
begin
  for r in select id from public.cell_print_licenses where paused_at is not null and pause_until <= now() loop
    perform public.cell_print_settle_pause(r.id);
    n := n + 1;
  end loop;
  return n;
end;$$;

create or replace function public.cell_print_pause(p_user uuid, p_key text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare lic public.cell_print_licenses;
begin
  select * into lic from public.cell_print_licenses where key=upper(btrim(p_key)) and owner_user_id=p_user for update;
  if not found or not lic.active then raise exception 'License not found'; end if;
  perform public.cell_print_settle_pause(lic.id);
  select * into lic from public.cell_print_licenses where id=lic.id;
  if lic.source='trial' then raise exception 'Not pausable: trial'; end if;
  if lic.expires_at is null then raise exception 'Not pausable: not activated'; end if;
  if lic.expires_at <= now() then raise exception 'Not pausable: expired'; end if;
  if lic.paused_at is not null then raise exception 'Not pausable: paused'; end if;
  if public.cell_print_pauses_left(lic.id) <= 0 then raise exception 'Pause limit'; end if;
  update public.cell_print_licenses set paused_at=now(), pause_until=now()+interval '14 days'
    where id=lic.id returning * into lic;
  insert into public.cell_print_pauses(license_id, user_id, started_at) values(lic.id, p_user, lic.paused_at);
  return jsonb_build_object('pausedAt', lic.paused_at, 'pauseUntil', lic.pause_until,
    'expiresAt', lic.expires_at, 'pausesLeft', public.cell_print_pauses_left(lic.id));
end;$$;

create or replace function public.cell_print_resume(p_user uuid, p_key text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare lic public.cell_print_licenses;
begin
  select * into lic from public.cell_print_licenses where key=upper(btrim(p_key)) and owner_user_id=p_user;
  if not found then raise exception 'License not found'; end if;
  perform public.cell_print_settle_pause(lic.id, true);
  select * into lic from public.cell_print_licenses where id=lic.id;
  return jsonb_build_object('expiresAt', lic.expires_at, 'pausesLeft', public.cell_print_pauses_left(lic.id));
end;$$;

-- Пробный ключ: один на ПК и один на аккаунт; аккаунтам с купленными ключами не выдаётся.
create or replace function public.cell_print_start_trial(p_user uuid, p_device_hash text, p_device_name text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare generated text; lic_id bigint;
begin
  if p_device_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  perform pg_advisory_xact_lock(hashtext('cell-trial:'||p_device_hash));
  if exists(select 1 from public.cell_print_trial_claims where device_hash=p_device_hash or user_id=p_user) then
    raise exception 'Trial used';
  end if;
  if exists(select 1 from public.cell_print_licenses where owner_user_id=p_user and coalesce(source,'')<>'trial') then
    raise exception 'Trial used: has keys';
  end if;
  loop
    generated:='CP-'||upper(substr(md5(random()::text),1,4))||'-'||upper(substr(md5(random()::text),5,4))||'-'||upper(substr(md5(random()::text),9,4));
    begin
      insert into public.cell_print_licenses(key,duration_days,device_limit,marketplace_scope,source,note,owner_user_id,activated_at,expires_at)
      values(generated,7,1,'both','trial','Пробный период',p_user,now(),now()+interval '7 days')
      returning id into lic_id;
      exit;
    exception when unique_violation then null; end;
  end loop;
  insert into public.cell_print_trial_claims(device_hash,user_id,license_id) values(p_device_hash,p_user,lic_id);
  insert into public.cell_print_activations(license_id, device_hash, device_name, activated_by)
    values(lic_id, p_device_hash, coalesce(p_device_name,''), p_user);
  return jsonb_build_object('key', generated, 'expiresAt', now()+interval '7 days');
end;$$;

-- Активация: как в 20261104, плюс снятие истёкшей паузы, отказ на паузе и поля trial/pausesLeft.
create or replace function public.activate_cell_print_license(
  p_key text, p_device_hash text, p_legacy_hash text default null,
  p_user uuid default null, p_device_name text default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare lic public.cell_print_licenses; count_devices integer;
begin
  if p_device_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  if p_legacy_hash is not null and p_legacy_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  select * into lic from public.cell_print_licenses where key=upper(btrim(p_key)) for update;
  if not found or not lic.active then raise exception 'Invalid license'; end if;
  if p_user is not null and lic.owner_user_id is not null and lic.owner_user_id <> p_user then
    raise exception 'Not owner';
  end if;
  if lic.paused_at is not null then
    perform public.cell_print_settle_pause(lic.id);
    select * into lic from public.cell_print_licenses where id=lic.id;
    if lic.paused_at is not null then
      raise exception 'License paused until %', to_char(lic.pause_until, 'YYYY-MM-DD"T"HH24:MI:SS"Z"');
    end if;
  end if;
  if lic.activated_at is null then
    update public.cell_print_licenses set activated_at=now(), expires_at=now()+make_interval(days=>duration_days)
      where id=lic.id returning * into lic;
  end if;
  if lic.expires_at <= now() then raise exception 'License expired'; end if;
  if exists(select 1 from public.cell_print_activations where license_id=lic.id and device_hash=p_device_hash and revoked_at is null) then
    update public.cell_print_activations set last_seen_at=now(),
      device_name=coalesce(nullif(p_device_name,''), device_name),
      activated_by=coalesce(activated_by, p_user)
      where license_id=lic.id and device_hash=p_device_hash and revoked_at is null;
  elsif p_legacy_hash is not null and exists(select 1 from public.cell_print_activations where license_id=lic.id and device_hash=p_legacy_hash and revoked_at is null) then
    update public.cell_print_activations set device_hash=p_device_hash, last_seen_at=now(),
      device_name=coalesce(nullif(p_device_name,''), device_name),
      activated_by=coalesce(activated_by, p_user)
      where license_id=lic.id and device_hash=p_legacy_hash and revoked_at is null;
  else
    if lic.require_account and p_user is null then raise exception 'Account required'; end if;
    select count(*) into count_devices from public.cell_print_activations where license_id=lic.id and revoked_at is null;
    if count_devices >= lic.device_limit then raise exception 'Device limit reached'; end if;
    insert into public.cell_print_activations(license_id, device_hash, device_name, activated_by)
      values(lic.id, p_device_hash, coalesce(p_device_name, ''), p_user);
  end if;
  if p_user is not null and lic.owner_user_id is null then
    update public.cell_print_licenses set owner_user_id=p_user where id=lic.id returning * into lic;
  end if;
  select count(*) into count_devices from public.cell_print_activations where license_id=lic.id and revoked_at is null;
  return jsonb_build_object('active', true, 'expiresAt', lic.expires_at, 'deviceLimit', lic.device_limit,
    'devicesUsed', count_devices, 'marketplaceScope', lic.marketplace_scope, 'serverTime', now(),
    'trial', coalesce(lic.source,'')='trial', 'pausesLeft', public.cell_print_pauses_left(lic.id));
end;$$;

-- Оплата: как в 20260917. Продление пробного ключа превращает его в обычный (source='payment'),
-- срок отсчитывается от сегодняшнего дня; активные ПК считаем без отозванных.
create or replace function public.complete_cell_print_order(p_order_id uuid)
returns text language plpgsql security definer set search_path=public as $$
declare o public.payment_orders; lic public.cell_print_licenses; generated text; active_devices integer;
begin
  select * into o from public.payment_orders where id=p_order_id and product_kind in
    ('cell_print_program','cell_print_license','cell_print_bundle') for update;
  if not found then raise exception 'Order not found'; end if;
  if o.status='succeeded' and o.cell_print_license_key is not null then return o.cell_print_license_key; end if;
  if o.renewal_target_key is not null then
    if o.product_kind<>'cell_print_license' or o.user_id is null then raise exception 'Invalid renewal'; end if;
    select * into lic from public.cell_print_licenses where key=o.renewal_target_key and owner_user_id=o.user_id for update;
    if not found then raise exception 'License not found'; end if;
    if o.cell_print_marketplace_scope is not null and o.cell_print_marketplace_scope<>lic.marketplace_scope then raise exception 'License scope mismatch'; end if;
    select count(*) into active_devices from public.cell_print_activations where license_id=lic.id and revoked_at is null;
    if active_devices>o.cell_print_device_limit then raise exception 'Device limit reached'; end if;
    update public.cell_print_licenses set duration_days=duration_days+o.cell_print_duration_days,
      device_limit=o.cell_print_device_limit,active=true,
      source=case when source='trial' then 'payment' else source end,
      expires_at=case when expires_at is null then null else greatest(now(),expires_at)+make_interval(days=>o.cell_print_duration_days) end
      where id=lic.id returning * into lic;
    generated:=lic.key;
  else
    loop
      generated:='CP-'||upper(substr(md5(random()::text),1,4))||'-'||upper(substr(md5(random()::text),5,4))||'-'||upper(substr(md5(random()::text),9,4));
      begin
        insert into public.cell_print_licenses(key,duration_days,device_limit,marketplace_scope,source,note,owner_user_id)
        values(generated,o.cell_print_duration_days,o.cell_print_device_limit,coalesce(o.cell_print_marketplace_scope,'wb'),'payment','Заказ '||p_order_id,o.user_id);
        exit;
      exception when unique_violation then null; end;
    end loop;
  end if;
  update public.payment_orders set cell_print_license_key=generated,status='succeeded',paid_at=coalesce(paid_at,now()),updated_at=now() where id=p_order_id;
  return generated;
end;$$;

do $$
declare f text;
begin
  foreach f in array array[
    'cell_print_pauses_left(bigint)', 'cell_print_settle_pause(bigint, boolean)', 'cell_print_settle_expired_pauses()',
    'cell_print_pause(uuid, text)', 'cell_print_resume(uuid, text)', 'cell_print_start_trial(uuid, text, text)',
    'activate_cell_print_license(text, text, text, uuid, text)', 'complete_cell_print_order(uuid)'
  ] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
end $$;

commit;
