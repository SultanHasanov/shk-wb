-- Связка «Печати ячеек» 2.2 с аккаунтом сайта: мягкий отзыв устройств, реестр ПК
-- по аккаунту и опциональный замок «только из моего аккаунта». Только добавления;
-- анонимная активация старых версий (p_user is null, require_account=false) не меняется.
begin;

-- Доп. поля активаций: имя ПК, версия, кто привязал, мягкий отзыв (освобождает место).
alter table public.cell_print_activations
  add column if not exists device_name text not null default '',
  add column if not exists app_version text not null default '',
  add column if not exists activated_by uuid references auth.users(id) on delete set null,
  add column if not exists revoked_at timestamptz;

-- Необязательный замок: новые ПК активируются только из аккаунта владельца.
-- По умолчанию false — поведение как раньше.
alter table public.cell_print_licenses
  add column if not exists require_account boolean not null default false;

-- Реестр компьютеров «Печати ячеек» по аккаунту: вход/refresh новых версий
-- регистрируют ПК здесь, а кабинет показывает и отзывает их.
create table if not exists public.cell_print_devices (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  device_hash text not null check (length(device_hash) = 64),
  name text not null default '',
  app_version text not null default '',
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  revoked_at timestamptz,
  unique(user_id, device_hash)
);
create index if not exists cell_print_devices_user_idx on public.cell_print_devices(user_id);

alter table public.cell_print_devices enable row level security;
revoke all on table public.cell_print_devices from anon, authenticated;
grant select, insert, update, delete on table public.cell_print_devices to service_role;

-- Активация ключа с необязательной привязкой к аккаунту. Та же сигнатура плюс
-- p_user и p_device_name. Старые вызовы (3 аргумента) по-прежнему работают.
drop function if exists public.activate_cell_print_license(text, text, text);
create or replace function public.activate_cell_print_license(
  p_key text, p_device_hash text, p_legacy_hash text default null,
  p_user uuid default null, p_device_name text default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare lic public.cell_print_licenses; count_devices integer;
begin
  if p_device_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  if p_legacy_hash is not null and p_legacy_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  select * into lic from public.cell_print_licenses where key=upper(btrim(p_key)) for update;
  if not found or not lic.active then raise exception 'Invalid license'; end if;
  -- Чужой ключ: у ключа есть владелец и запрос от другого аккаунта.
  if p_user is not null and lic.owner_user_id is not null and lic.owner_user_id <> p_user then
    raise exception 'Not owner';
  end if;
  if lic.activated_at is null then
    update public.cell_print_licenses set activated_at=now(), expires_at=now()+make_interval(days=>duration_days)
      where id=lic.id returning * into lic;
  end if;
  if lic.expires_at <= now() then raise exception 'License expired'; end if;
  -- Устройство уже активно (не отозвано) — обновляем метки.
  if exists(select 1 from public.cell_print_activations where license_id=lic.id and device_hash=p_device_hash and revoked_at is null) then
    update public.cell_print_activations set last_seen_at=now(),
      device_name=coalesce(nullif(p_device_name,''), device_name),
      activated_by=coalesce(activated_by, p_user)
      where license_id=lic.id and device_hash=p_device_hash and revoked_at is null;
  elsif p_legacy_hash is not null and exists(select 1 from public.cell_print_activations where license_id=lic.id and device_hash=p_legacy_hash and revoked_at is null) then
    update public.cell_print_activations set device_hash=p_device_hash, last_seen_at=now(),
      device_name=coalesce(nullif(p_device_name,''), device_name),
      activated_by=coalesce(activated_by, p_user)
      where license_id=lic.id and device_hash=p_legacy_hash and revoked_at is null;
  else
    -- Новое устройство. Замок блокирует только новые ПК: уже активные работают и без аккаунта.
    if lic.require_account and p_user is null then raise exception 'Account required'; end if;
    select count(*) into count_devices from public.cell_print_activations where license_id=lic.id and revoked_at is null;
    if count_devices >= lic.device_limit then raise exception 'Device limit reached'; end if;
    insert into public.cell_print_activations(license_id, device_hash, device_name, activated_by)
      values(lic.id, p_device_hash, coalesce(p_device_name, ''), p_user);
  end if;
  -- Первая активация из аккаунта — закрепляем владельца.
  if p_user is not null and lic.owner_user_id is null then
    update public.cell_print_licenses set owner_user_id=p_user where id=lic.id returning * into lic;
  end if;
  select count(*) into count_devices from public.cell_print_activations where license_id=lic.id and revoked_at is null;
  return jsonb_build_object('active', true, 'expiresAt', lic.expires_at, 'deviceLimit', lic.device_limit,
    'devicesUsed', count_devices, 'marketplaceScope', lic.marketplace_scope, 'serverTime', now());
end;$$;
revoke all on function public.activate_cell_print_license(text, text, text, uuid, text) from public, anon, authenticated;
grant execute on function public.activate_cell_print_license(text, text, text, uuid, text) to service_role;

-- Кандидаты для привязки: активные неистёкшие лицензии аккаунта со сведениями о местах.
create or replace function public.cell_print_link_candidates(p_user uuid, p_device_hash text)
returns jsonb language sql security definer set search_path=public as $$
  select coalesce(jsonb_agg(row order by created_at desc), '[]'::jsonb) from (
    select l.created_at, jsonb_build_object(
      'key', l.key, 'scope', l.marketplace_scope, 'expiresAt', l.expires_at,
      'durationDays', l.duration_days, 'deviceLimit', l.device_limit, 'requireAccount', l.require_account,
      'devicesUsed', (select count(*) from public.cell_print_activations a where a.license_id=l.id and a.revoked_at is null),
      'thisDevice', exists(select 1 from public.cell_print_activations a where a.license_id=l.id and a.device_hash=p_device_hash and a.revoked_at is null)
    ) as row
    from public.cell_print_licenses l
    where l.owner_user_id=p_user and l.active and (l.expires_at is null or l.expires_at>now())
  ) q;
$$;
revoke all on function public.cell_print_link_candidates(uuid, text) from public, anon, authenticated;
grant execute on function public.cell_print_link_candidates(uuid, text) to service_role;

-- Регистрация/обновление ПК в реестре аккаунта. Возвращает revoked — отозван ли ПК.
create or replace function public.cell_print_register_device(p_user uuid, p_device_hash text, p_name text default null, p_version text default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare dev public.cell_print_devices;
begin
  if p_device_hash !~ '^[0-9a-f]{64}$' then raise exception 'Invalid device'; end if;
  insert into public.cell_print_devices(user_id, device_hash, name, app_version)
    values(p_user, p_device_hash, coalesce(p_name, ''), coalesce(p_version, ''))
  on conflict(user_id, device_hash) do update set
    last_seen_at=now(),
    name=coalesce(nullif(excluded.name, ''), public.cell_print_devices.name),
    app_version=coalesce(nullif(excluded.app_version, ''), public.cell_print_devices.app_version)
  returning * into dev;
  return jsonb_build_object('revoked', dev.revoked_at is not null);
end;$$;
revoke all on function public.cell_print_register_device(uuid, text, text, text) from public, anon, authenticated;
grant execute on function public.cell_print_register_device(uuid, text, text, text) to service_role;

-- Список ПК аккаунта для кабинета.
create or replace function public.cell_print_devices_list(p_user uuid)
returns jsonb language sql security definer set search_path=public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'deviceHash', device_hash, 'name', name, 'appVersion', app_version,
    'lastSeenAt', last_seen_at, 'revokedAt', revoked_at
  ) order by last_seen_at desc), '[]'::jsonb)
  from public.cell_print_devices where user_id=p_user and revoked_at is null;
$$;
revoke all on function public.cell_print_devices_list(uuid) from public, anon, authenticated;
grant execute on function public.cell_print_devices_list(uuid) to service_role;

-- Мягкий отзыв ПК в кабинете: отзываем запись реестра и все активации этого ПК по
-- ключам аккаунта — место освобождается, но история не удаляется.
create or replace function public.cell_print_revoke_device(p_user uuid, p_device_hash text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare freed integer;
begin
  update public.cell_print_devices set revoked_at=now()
    where user_id=p_user and device_hash=p_device_hash and revoked_at is null;
  update public.cell_print_activations a set revoked_at=now()
    from public.cell_print_licenses l
    where a.license_id=l.id and l.owner_user_id=p_user and a.device_hash=p_device_hash and a.revoked_at is null;
  get diagnostics freed = row_count;
  return jsonb_build_object('ok', true, 'freed', freed);
end;$$;
revoke all on function public.cell_print_revoke_device(uuid, text) from public, anon, authenticated;
grant execute on function public.cell_print_revoke_device(uuid, text) to service_role;

commit;
