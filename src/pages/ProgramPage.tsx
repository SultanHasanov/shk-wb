        <Button onClick={() => share(t('«Помощник ПВЗ» для Windows', '«ПВЗ көмекшісі» Windows үшін'))}>
          <Send size={18} />
          {t('Ссылка на ПК', 'ДК-ға сілтеме')}
        </Button>
