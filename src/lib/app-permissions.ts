/** Какой шаблон совпадает с набором закрытого (порядок не важен). */
export function matchingPreset(presets: PermissionPreset[], denied: string[]) {
  const set = new Set(denied);
  return presets.find(p => p.denied.length === set.size && p.denied.every(k => set.has(k)))?.id ?? null;
}
